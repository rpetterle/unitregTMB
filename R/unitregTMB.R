## unitregTMB.control
## ----------------------------------------------------------------------------
#' @title Control Parameters for unitregTMB Model Fitting
#' 
#' @description 
#' Defines control parameters for the optimization process used in \code{unitregTMB}. 
#' It allows the user to specify evaluation and iteration limits, the choice of 
#' optimizer, and whether to compute standard errors via the TMB framework.
#' 
#' @param eval.max Maximum number of evaluations of the objective function allowed. Default is 2000.
#' @param iter.max Maximum number of iterations allowed. Default is 2000.
#' @param verbose Logical; if \code{TRUE}, optimization tracing information is printed. Default is \code{FALSE}.
#' @param sd.report Logical; if \code{TRUE}, standard errors are calculated using \code{TMB::sdreport}. Default is \code{TRUE}.
#' @param get.joint.precision Logical; if \code{TRUE}, the joint precision matrix is returned by \code{sdreport}. Default is \code{FALSE}.
#' @param optimizer A character string specifying the optimizer to use. Options are \code{"nlminb"} (default) or \code{"optim"}.
#' @param optim.method The method to be used if \code{optimizer = "optim"}. Default is \code{"BFGS"}.
#' @param optim.control A list of additional control parameters to be passed to the chosen optimizer.
#' @param ... Additional arguments.
#' 
#' @return A list containing the specified control parameters to be used in \code{unitregTMB.fit}.
#' 
#' @export
unitregTMB.control <- function(eval.max = 2000, 
                               iter.max = 2000,
                               verbose = FALSE, 
                               sd.report = TRUE, 
                               get.joint.precision = FALSE, 
                               optimizer = c("nlminb", "optim"),
                               optim.method = "BFGS",
                               optim.control = list(),
                               ...) {
  optimizer <- match.arg(optimizer)
  list(
    eval.max = eval.max, iter.max = iter.max, verbose = verbose,
    sd.report = sd.report, get.joint.precision = get.joint.precision, 
    optimizer = optimizer, optim.method = optim.method, optim.control = optim.control,
    ...
  )
}

