## unitregTMB.fit
## ----------------------------------------------------------------------------
#' Fit a unitregTMB Model (Internal)
#' 
#' @description 
#' Internal function that acts as a wrapper for \code{TMB::MakeADFun} and the 
#' optimization algorithms (\code{nlminb} or \code{optim}) to fit the regression model.
#' 
#' @param data_tmb A list of data objects created internally by \code{unitregTMB} to be passed to TMB.
#' @param parameters A list of initial parameter values.
#' @param random_args A character vector indicating which parameters should be treated as random effects.
#' @param control A list of control parameters generated by \code{unitregTMB.control}.
#' @param silent Logical; if \code{TRUE}, disables TMB compilation and evaluation output.
#' 
#' @return A list containing the fitted TMB object, the optimization result, the standard error report, and convergence metrics.
#' 
#' @keywords internal
unitregTMB.fit <- function(data_tmb, parameters, random_args = NULL,
                           control = unitregTMB.control(), silent = FALSE) {
  
  obj <- TMB::MakeADFun(
    data = data_tmb, parameters = parameters, random = random_args,
    DLL = "unitregTMB", silent = silent
  )
  
  start_time <- Sys.time()
  optimizer_warnings <- character()
  
  capture_optimizer_warnings <- function(expr) {
    withCallingHandlers(
      expr,
      warning = function(w) {
        optimizer_warnings <<- c(optimizer_warnings, conditionMessage(w))
        if (!silent) message("Optimizer warning: ", conditionMessage(w))
        invokeRestart("muffleWarning")
      }
    )
  }
  
  if (control$optimizer == "nlminb") {
    nlminb_control <- modifyList(
      list(iter.max = control$iter.max, eval.max = control$eval.max, trace = if(control$verbose) 1 else 0),
      control$optim.control
    )
    opt <- capture_optimizer_warnings(
      nlminb(start = obj$par, objective = obj$fn, gradient = obj$gr, control = nlminb_control)
    )
  } else if (control$optimizer == "optim") {
    opt <- capture_optimizer_warnings(
      optim(par = obj$par, fn = obj$fn, gr = obj$gr, method = control$optim.method, control = control$optim.control)
    )
    opt$objective <- opt$value
  } else { stop("Unsupported optimizer.") }
  
  fitting_time <- as.numeric(difftime(Sys.time(), start_time, units = "secs"))
  
  raw_grad <- tryCatch(
    obj$gr(opt$par),
    error = function(e) {
      optimizer_warnings <<- c(optimizer_warnings, paste0("Final gradient evaluation failed: ", conditionMessage(e)))
      rep(NA_real_, length(opt$par))
    }
  )
  
  if (all(is.finite(raw_grad))) {
    max_grad <- max(abs(raw_grad))
  } else {
    max_grad <- Inf
  }
  
  sd_report <- NULL
  if (control$sd.report) {  
    if(control$verbose) cat("Calculating standard errors...\n")
    sd_report <- tryCatch({
      TMB::sdreport(obj, getJointPrecision = control$get.joint.precision)
    }, error = function(e) { 
      warning("sdreport failed: ", conditionMessage(e)); NULL 
    })
  }
  
  return(list(obj = obj, opt = opt, sd_report = sd_report, 
              convergence = opt$convergence, message = opt$message, 
              max_gradient = max_grad, full_gradient = raw_grad, 
              optimizer_warnings = unique(optimizer_warnings), 
              fitting_time = fitting_time))
}

